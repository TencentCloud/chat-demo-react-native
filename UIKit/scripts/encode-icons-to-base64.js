// 一次性脚本：把 src/ 下所有 PNG 转 base64，生成 iconBase64.ts
// 运行：node scripts/encode-icons-to-base64.js
//
// v18.81.2 升级：扫整个 src/ 下所有 PNG（不只是 src/static/icon/）
//   覆盖：
//     - src/static/icon/（44 个）
//     - src/static/assets/message-list/（4 个）
//     - src/static/*.png（4 个 BottomTabBar 用：message/relation/selected）
//     - src/components/*/assets/（6 个：ChatSetting 4 + MessageList 2）
//   key 命名：相对 src/ 的完整路径（例 "static/icon/search.png" /
//     "components/ChatSetting/assets/nvue_arrow-right.png"）
//   消费方：
//     import { iconAssets } from '../../static/iconBase64'
//     <Image source={iconAssets['static/icon/search.png']} />
//
// 折行：base64 字符串按 76 字符折行（RFC 4648 标准）
//   防止 Metro/Babel/Hermes 解析超长单行时静默失败
//   （v18.81 经验：recording_bg.png base64 67K 字符放单行 → 整个包所有 icon 不显示）
const fs = require('fs')
const path = require('path')

const SRC_ROOT = path.join(__dirname, '../src')
const OUT_FILE = path.join(__dirname, '../src/static/iconBase64.ts')

// 每 76 个 base64 字符折一行（标准 RFC 4648 折行宽度）
const BASE64_LINE_WIDTH = 76

function wrapBase64(b64) {
  const lines = []
  for (let i = 0; i < b64.length; i += BASE64_LINE_WIDTH) {
    lines.push(b64.slice(i, i + BASE64_LINE_WIDTH))
  }
  return lines.join('\\\n    ')
}

function walk(dir, prefix) {
  const out = []
  if (!fs.existsSync(dir)) return out
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name)
    const rel = prefix ? `${prefix}/${name}` : name
    const stat = fs.statSync(full)
    if (stat.isDirectory()) {
      // 跳过 node_modules 等
      if (name === 'node_modules' || name.startsWith('.')) continue
      out.push(...walk(full, rel))
    } else if (name.endsWith('.png')) {
      out.push({ rel, full })
    }
  }
  return out
}

const files = walk(SRC_ROOT, '').sort((a, b) => a.rel.localeCompare(b.rel))
const lines = []
lines.push('// auto-generated by scripts/encode-icons-to-base64.js — do not edit')
lines.push('// 把 src/ 下所有 PNG 编码为 base64，inline 进 JS bundle')
lines.push('// 解决 iOS symlink 包资源不进 app bundle 问题（v18.74 经验）')
lines.push('//')
lines.push('// v18.81.1 修复：base64 字符串按 76 字符折行（RFC 4648 标准折行宽度）')
lines.push('//   之前 v18.81 单行 67K 字符（recording_bg.png）Metro 解析超长单行静默失败')
lines.push('//   → 整个包所有 icon 不显示（不只是 recording_bg.png）')
lines.push('//')
lines.push('// v18.81.2 升级：扫整个 src/ 下所有 PNG（不只 src/static/icon/）')
lines.push('//   覆盖 static/icon/ + static/assets/ + static/*.png + components/*/assets/')
lines.push('//   key 命名：相对 src/ 完整路径（"static/icon/search.png" 等）')
lines.push('//')
lines.push('// 使用方式：')
lines.push('//   import { iconAssets } from "../../static/iconBase64"')
lines.push('//   <Image source={iconAssets["static/icon/search.png"]} />')
lines.push('')
lines.push('export interface IconAsset {')
lines.push('  uri: string')
lines.push('}')
lines.push('')
lines.push('export const iconAssets: Record<string, IconAsset> = {')
for (const f of files) {
  const b64 = fs.readFileSync(f.full).toString('base64')
  const wrapped = wrapBase64(b64)
  lines.push(`  '${f.rel}': { uri: \`data:image/png;base64,${wrapped}\` },`)
}
lines.push('}')
lines.push('')
lines.push('export const iconAssetKeys: string[] = [')
for (const f of files) {
  lines.push(`  '${f.rel}',`)
}
lines.push(']')
lines.push('')

fs.writeFileSync(OUT_FILE, lines.join('\n'))
const totalBytes = files.reduce((s, f) => s + fs.statSync(f.full).size, 0)
console.log(`Wrote ${OUT_FILE}`)
console.log(`  - ${files.length} icons`)
console.log(`  - ${(totalBytes / 1024).toFixed(1)} KB source PNG`)
console.log(`  - line width ${BASE64_LINE_WIDTH}`)
